/** The icon of a space by its name; an unknown name gets the circle. */
fun spaceIcon(name: String): ImageVector =
    synchronized(icons) {
        icons.getOrPut(name) {
            val path = SPACE_ICON_PATHS[name] ?: SPACE_ICON_PATHS.getValue("circle")
            ImageVector.Builder(
                name = "space-$name",
                defaultWidth = ICON_BOX.dp,
                defaultHeight = ICON_BOX.dp,
                viewportWidth = ICON_BOX,
                viewportHeight = ICON_BOX,
            )
                .addPath(
                    pathData = addPathNodes(path.data),
                    pathFillType = if (path.evenOdd) PathFillType.EvenOdd else PathFillType.NonZero,
                    fill = SolidColor(Color.Black),
                )
                .build()
        }
    }
